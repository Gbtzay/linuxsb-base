function readInput(root, file) {
  const source = readFileSync(join(root, file), 'utf8')
  if (source.charCodeAt(0) === 0xfeff) throw new Error(`${file}：源码带 UTF-8 BOM`)
  if (/\r/.test(source)) throw new Error(`${file}：源码含 CRLF 行尾，请保存为 LF`)
  // Each input must own complete blocks; pairing across files hides extraction mistakes.
  try { applyPluginBuildProfile('skin', source, 'dev') } catch (error) {
    throw new Error(`${file}：${error.message}`, { cause: error })
  }
  return source
}

export function composeSkinSource({ root = repoRoot } = {}) {
  const template = readInput(root, 'plugins/skin/skin.template.js')
  let source = template
  for (const { file, marker } of modules) {
    const input = readInput(root, `plugins/skin/${file}`)
    if (/^[ \t]*\/\/ @LSB_SKIN_(?:CANVAS_STATE|STYLES|MEDIA|PLUGIN_CATALOG|SEARCH|NAVIGATION|CONTENT|HISTORY|PROFILE|SITE_CARDS|ONLINE|ASIDE_CARDS|ASIDE_VIEWS|CONFIG|SPA_DOCUMENT|VIEW_CACHE|SPA|HOME_INFINITE|NATIVE_ENHANCEMENTS|SETTINGS|TOPBAR|TIMELINE|SELECTION|APPEARANCE|SURFACE_LAYOUT|CANVAS_SCROLL|WINDOWS|CANVAS_HOST|RUNTIME)[ \t]*$/m.test(input)) {
      throw new Error(`${file}：模块不能包含模板注入标记`)
    }
    const injection = new RegExp(`^([ \\t]*)// ${marker}[ \\t]*$`, 'gm')
    if ([...template.matchAll(injection)].length !== 1 || [...source.matchAll(injection)].length !== 1) {
      throw new Error(`skin 模板必须包含唯一的 ${marker} 注入标记，模块不能复制注入点`)
    }
    const body = input.replace(/^export (?=(?:const|let|var|function|class)\b)/gm, '').trimEnd()
    source = source.replace(injection, (_, indent) => body.split('\n').map((line) => line ? indent + line : '').join('\n'))
  }
  source = source.replace(/^(\/\/ ==\/UserScript==\n)/m, '$1' + notice)
  new Script(source, { filename: 'plugins/skin.user.js' })
  return source
}

export function syncSkinSource({ root = repoRoot, check = false } = {}) {
  const source = composeSkinSource({ root })
  const output = join(root, 'plugins/skin.user.js')
  const current = existsSync(output) ? readFileSync(output, 'utf8') : null
  if (source !== current) {
    if (check) throw new Error('plugins/skin.user.js 生成文件过期或缺失，请运行 npm run build:skin')
    writeFileSync(output, source)
  }
  return source
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  if (args.some((arg) => arg !== '--check')) throw new Error('用法：node scripts/build-skin.mjs [--check]')
  const check = args.includes('--check')
  syncSkinSource({ check })
  console.log(check ? '✔ skin 生成文件与拆分源码一致' : '✔ plugins/skin.user.js 已从拆分源码生成')
}
